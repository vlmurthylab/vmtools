# GLI coefficients used by predict_FEV1() and predict_FVC().
# The base coefficients (a, p, q) are used by both methods; the Mspline/Sspline polynomials
# only by method = "polynomial" (method = "lookup" uses the tables in R/sysdata.rda).
#
# Base coefficients:
#   GLI-2012: Quanjer PH, et al. Eur Respir J 2012;40:1324-43 (official GLI workbook lookuptables.xls,
#             online supplement to that paper: https://publications.ersnet.org/content/erj/40/6/1324;
#             FEV1 values match Tables E1 and E3 of the GLI memo 'Implementing GLI 2012 lung function
#             regression equations', 19 July 2015).
#   GLI-Global: Bowerman C, et al. Am J Respir Crit Care Med 2023;207:768-74, online supplement
#               Table E2 (checked against the equations in the official GLI Global lookup-table workbook).
#   M = exp(a0 + a1*ln(height) + a2*ln(age) + [GLI-2012 ethnic terms a3..a6] + Mspline)
#   S = exp(p0 + p1*ln(age) + [GLI-2012 ethnic terms p2..p5] + Sspline)
#   L = q0 + q1*ln(age)          (Lspline is zero for FEV1 and FVC)
#   Ethnic terms (GLI-2012 only): 3/p2 African American, 4/p3 North East Asian,
#   5/p4 South East Asian, 6/p5 Other/mixed; Caucasian is the reference (all zero).
#
# Age splines (Mspline, Sspline):
#   Fitted by vmtools to the official GLI lookup tables (ages 3-95, every 0.25 y) as three
#   fifth-order polynomials in (age/100) - the form used by the GLI memo for adults - on
#   ages 3-12, 12-25 and 25-95. The 25-95 piece is a minimax fit; the 12-25 and 3-12 pieces
#   are minimax fits constrained to match the value and slope of the next-older piece at
#   ages 25 and 12, so the curves are smooth with no jumps. Each row gives c0..c5 for
#   c0 + c1*(age/100) + ... + c5*(age/100)^5.
#
# Why not GLI's own adult polynomials? GLI published 25-95 y polynomials only for adults: FEV1 and
# FVC in its workbook lookuptables.xls (online supplement to Quanjer 2012), and FEV1 in its 2015
# implementation memo. The workbook's male FEV1 polynomial has two erroneous coefficients (b4 = 0, c4 = -220.3631; the memo gives
# -0.1215 and -109.6777), and earlier versions of vmtools (before 0.1.0) mistranscribed the
# workbook's female FVC b4 (+0.973) as -0.9730. The polynomials here were refitted to the
# official tables for ages 3-95 and are checked against them in tests/testthat/test-spirometry.R.

